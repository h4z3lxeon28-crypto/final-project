#!/bin/bash
# سكربت Bash لحساب الفائدة البسيطة
# مخصص للمشروع النهائي - 2026

echo "--- حساب الفائدة البسيطة ---"

echo "أدخل المبلغ الأساسي (Principal):"
read p

echo "أدخل معدل الفائدة السنوي (Rate of Interest):"
read r

echo "أدخل الفترة الزمنية بالسنوات (Time Period):"
read t

# عملية الحساب الرياضية
s=$(( p * r * t / 100 ))

echo "-------------------------------------"
echo "إجمالي الفائدة البسيطة المحسوبة هي: $s"
echo "-------------------------------------"
